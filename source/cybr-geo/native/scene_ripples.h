struct RippleField {
 static constexpr int NX=801,NY=641;
 float x0,y0,sx,sy;
 std::vector<V> samples; // height offset, d(height)/dx, d(height)/dy
 V at(float x,float y)const{
  float u=clamp((x-x0)*sx,0.f,NX-1.0001f),v=clamp((y-y0)*sy,0.f,NY-1.0001f);
  int ix=int(u),iy=int(v);float fx=u-ix,fy=v-iy;
  return (samples[size_t(iy)*NX+ix]*(1-fx)+samples[size_t(iy)*NX+ix+1]*fx)*(1-fy)
       +(samples[size_t(iy+1)*NX+ix]*(1-fx)+samples[size_t(iy+1)*NX+ix+1]*fx)*fy;
 }
};
std::array<RippleField,2> rippleFields;
void initRipples(){
 for(int i=0;i<2;i++){
  auto&f=rippleFields[i];const auto&p=pools[i];f.x0=p.x-p.rx*1.35f;f.y0=p.y-p.ry*1.35f;
  f.sx=(f.NX-1)/(2.70f*p.rx);f.sy=(f.NY-1)/(2.70f*p.ry);f.samples.resize(size_t(f.NX)*f.NY);
  #pragma omp parallel for schedule(static)
  for(int y=0;y<f.NY;y++)for(int x=0;x<f.NX;x++){
   double xx=f.x0+x/double(f.sx),yy=f.y0+y/double(f.sy),h=0,dx=0,dy=0;
   for(const auto&m:(sceneStyle==1?COAST_MODES:FOREST_MODES)){double phase=m[0]*xx+m[1]*yy+m[3]+.37*i,s=std::sin(phase),c=std::cos(phase);h+=m[2]*s;dx+=m[2]*m[0]*c;dy+=m[2]*m[1]*c;}
   f.samples[size_t(y)*f.NX+x]=V(float(h*RIPPLE_SCALE),float(dx*RIPPLE_SCALE),float(dy*RIPPLE_SCALE));
  }
 }
}
